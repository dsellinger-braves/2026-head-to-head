-- 2. Player Valuations Table (Supports 3-Year Keeper and Single-Year Redraft Models)
CREATE TABLE IF NOT EXISTS public.player_valuations (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    season_year INT NOT NULL DEFAULT 2026,
    player_id INT NOT NULL,
    fangraphs_id VARCHAR(32),
    mlbam_id INT,
    player_name TEXT NOT NULL,
    team TEXT,
    position TEXT,
    model_type TEXT NOT NULL, -- '3_YEAR_KEEPER' or 'SINGLE_SEASON'
    total_pr NUMERIC(6,2) NOT NULL,
    model_rank INT NOT NULL,
    model_price INT NOT NULL,
    espn_rank INT,
    espn_price INT,
    surplus_value INT, -- (model_price - espn_price)
    category_prs JSONB NOT NULL DEFAULT '{}'::jsonb,
    projected_stats JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT unique_season_player_model UNIQUE (season_year, player_id, model_type)
);

CREATE INDEX IF NOT EXISTS idx_player_valuations_season_model ON public.player_valuations(season_year, model_type);
CREATE INDEX IF NOT EXISTS idx_player_valuations_player_id ON public.player_valuations(player_id);
CREATE INDEX IF NOT EXISTS idx_player_valuations_rank ON public.player_valuations(model_rank);

